function makeHero(
  key: keyof typeof INITIAL_HERO_ROSTER,
  x: number,
  y: number,
  extra: Partial<Unit> = {}
): Unit {
  const base = INITIAL_HERO_ROSTER[key];
  return {
    ...base,
    mines: { ...base.mines },
    x,
    y,
    acted: false,
    moved: false,
    stunnedTurns: 0,
    poisonedTurns: 0,
    alive: true,
    facing: 'right',
    ...extra,
  };
}

function makeEnemy(
  cfg: Omit<Unit, 'faction' | 'canLayMines' | 'acted' | 'moved' | 'stunnedTurns' | 'mines' | 'healItems' | 'alive' | 'facing'> & {
    facing?: 'left' | 'right';
  }
): Unit {
  return {
    faction: 'enemy',
    canLayMines: false,
    acted: false,
    moved: false,
    stunnedTurns: 0,
    poisonedTurns: 0,
    mines: makeMineInventory(),
    healItems: 0,
    alive: true,
    facing: 'left',
    ...cfg,
  };
}

