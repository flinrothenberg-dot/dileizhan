const LEGEND: Record<string, TerrainType> = {
  '.': 'grass',
  'R': 'dirt_road',
  'F': 'forest',
  'H': 'house',
  'T': 'watchtower',
  'W': 'water',
  'B': 'bridge',
  'X': 'rock',
  'C': 'courtyard',
};

function parseMap(rows: string[]): TerrainType[][] {
  return rows.map((row) => row.split('').map((ch) => LEGEND[ch] ?? 'grass'));
}

